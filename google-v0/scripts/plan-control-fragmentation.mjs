import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {planControlMigration} from '../lib/control-fragments.mjs';
import {encodeFields} from '../lib/firestore.mjs';
const [input,output,...rest]=process.argv.slice(2);
if(!input||!output||rest.length||resolve(input)===resolve(output))throw Error('Use input.json output.json, different paths.');
const source=JSON.parse(readFileSync(input,'utf8')),plan=planControlMigration(source);
plan.commit={writes:plan.writes.map(w=>({update:{name:plan.prefix+w.path,fields:encodeFields(w.data??w.changes)},...(w.changes?{updateMask:{fieldPaths:Object.keys(w.changes)}}:{}),currentDocument:w.exists===false?{exists:false}:{updateTime:w.updateTime}}))};
const bytes=Buffer.byteLength(JSON.stringify(plan.commit));if(bytes>=10000000||plan.commit.writes.length>40)throw Error('Migration plan exceeds bounded commit.');
plan.commit_bytes=bytes;
writeFileSync(output,JSON.stringify(plan,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({applied:false,writes:plan.commit.writes.length,commit_bytes:bytes,original_snapshots_preserved:true,requires_independent_review:true}));
